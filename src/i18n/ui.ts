export const UI: Record<Lang, Record<UIKey, string>> = { nl, en };

export type T = (key: UIKey, vars?: Record<string, string | number>) => string;

export function useTranslations(lang: Lang): T {
  return (key, vars) => {
    let text = UI[lang][key] ?? UI.nl[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

/** Translate a Supabase/Postgres error to a friendly message. */
export function errorMessage(t: T, error: unknown) {
  const message = (error as { message?: string } | null)?.message ?? String(error);
  const key = `error.${message}` as UIKey;
  return key in nl ? t(key) : t("common.error", { message });
}

export function locale(lang: Lang) {
  return lang === "nl" ? "nl-NL" : "en-GB";
}

/** Path for a page in a language, without the deployment base: ("en", "/reserve") -> "/en/reserve". */
export function localePath(lang: Lang, path = "/") {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === DEFAULT_LANG) return clean;
  return clean === "/" ? `/${lang}/` : `/${lang}${clean}`;
}

/** Splits a base-less pathname into its language and the language-neutral path. */
export function splitLang(pathname: string): { lang: Lang; path: string } {
  const match = /^\/(en)(\/.*)?$/.exec(pathname);
  if (match) return { lang: "en", path: match[2] || "/" };
  return { lang: DEFAULT_LANG, path: pathname || "/" };
}

/** getStaticPaths for pages under src/pages/[...lang]. */
export function langPaths() {
  return LANGS.map((lang) => ({ params: { lang: lang === DEFAULT_LANG ? undefined : lang }, props: { lang } }));
}
